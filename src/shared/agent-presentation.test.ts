import assert from 'node:assert/strict';
import { commandPresentation, activityPresentation, permissionPresentation } from './agent-presentation';
import { autonomyDescriptions } from './autonomy';
import { english } from './translations';
import { setLanguage, t } from './locale';
setLanguage('ru');
assert.equal(commandPresentation('npm run build').title, 'Сборка проекта');
assert.equal(commandPresentation('git commit -m "fix"').title, 'Создание коммита');
assert.equal(commandPresentation('npm run build && rm -rf data').destructive, true);
assert.equal(commandPresentation('rm -rf node_modules').destructive, true);
assert.equal(commandPresentation('find . -delete').destructive, true);
assert.equal(commandPresentation('ls && find . -delete').destructive, true);
assert.equal(commandPresentation('find . -exec python3 dangerous.py {} ;').title, 'Выполнение команды');
assert.equal(commandPresentation('rg --pre python3 pattern file').title, 'Выполнение команды');
assert.equal(commandPresentation('echo "rm -rf /"').destructive, undefined);
assert.equal(permissionPresentation('file_delete', 'write_file: {"path":"app.ts"}').title, 'Изменение проекта');
assert.equal(activityPresentation({ id: 'x', label: 'observation_read', toolName: 'observation_read' }).title, 'Анализ предыдущих результатов');
for (const info of Object.values(autonomyDescriptions)) for (const value of Object.values(info)) assert(english[value], `Missing English translation: ${value}`);
setLanguage('en');
assert.equal(t(autonomyDescriptions.autonomous.name), 'Absolute Autopilot');
assert.equal(commandPresentation('pnpm install').title, 'Installing dependencies');
assert.equal(permissionPresentation('file_delete', 'delete_file: {}').title, 'Deleting files');
console.log('Russian/English autonomy and operation presentation; ambiguous commands remain conservative.');

setLanguage('ru');
assert.equal(commandPresentation("cd '/a space' && ls client/client/src/localization/dictionaries/ && cat package.json && ls python/ server/python/").description, 'Покажет словари локализации, настройки package.json и каталоги Python-скриптов.');
assert.equal(commandPresentation('git status --short --branch && git log --oneline -3 && df -h && nvidia-smi').title, 'Проверка Git и ресурсов системы');
assert.equal(commandPresentation('pip install -r requirements.txt').description, 'Установит пакеты из requirements.txt.');
assert.equal(commandPresentation('rm -rf ./old-model-cache').title, 'Удаление каталога');
assert.equal(commandPresentation('ls "a&&b"; cat "c|d"').title, 'Проверка структуры проекта');
assert.equal(commandPresentation("rg 'a; b' src | head -20").title, 'Проверка структуры проекта');
assert.equal(commandPresentation('npm run build || npm test').title, 'Несколько операций');
assert.equal(commandPresentation('ls\ncat package.json').title, 'Проверка структуры проекта');
assert.equal(commandPresentation("python -c 'print(\"a&&b\")'").title, 'Выполнение Python');
for (const input of ['cat $(rm -rf x)', 'ls > output', 'cat <(python script)', 'ls "unterminated', 'unknown && ls', 'ls &&', 'ls &', 'echo "rm -rf /"', 'ls "$HOME"']) assert.equal(commandPresentation(input).title, 'Выполнение команды', input);
assert.equal(commandPresentation('ls "a' + '\\' + '";rm x"').destructive, undefined);
setLanguage('en');
assert.equal(commandPresentation('pip install -r requirements.txt').description, 'Install packages from requirements.txt.');
assert.equal(commandPresentation('rm -rf ./old-model-cache').title, 'Deleting a directory');
assert.equal(activityPresentation({ id:'terminal', kind:'terminal', terminal: {command:'git status', cwd:'/project'} } as Parameters<typeof activityPresentation>[0]).context, '/project');
