import assert from 'node:assert/strict';
import { modelLanguageGuidance } from './model-language';
import { setLanguage } from './locale';
import { chatSystemContext } from '../main/services/capabilities';
setLanguage('ru');
const russianUi = chatSystemContext({ webAvailable: false });
assert.match(russianUi, /Choose the response language from the user’s messages and conversation context/);
assert.match(russianUi, /Follow explicit user requests for a language/);
assert.doesNotMatch(russianUi, /Язык интерфейса: русский|prefer Russian|предпочитай русский|model-provided reasoning/i);
setLanguage('en');
const englishUi = chatSystemContext({ webAvailable: false });
assert.match(englishUi, /Choose the response language from the user’s messages and conversation context/);
assert.doesNotMatch(englishUi, /Interface language: English|prefer English|model-provided reasoning/i);
assert.equal(russianUi, englishUi, 'model language guidance is independent of interface locale');
assert.doesNotMatch(modelLanguageGuidance, /reasoning|thinking|interface language/i);
setLanguage('ru');
