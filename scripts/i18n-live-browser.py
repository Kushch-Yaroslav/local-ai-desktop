FIXED_KEYS = {"panelTitle", "urlPlaceholder"}  # identical in every locale


def main():
    for locale in ["en"] + sorted(LOCALES):
        path = os.path.join(MESSAGES, f"{locale}.json")
        with open(path) as f:
            data = json.load(f)
        translations = EN if locale == "en" else {
            f"liveBrowser.{k}": v for k, v in LOCALES[locale].items()
        }
        # Fill fixed keys with the English text (brand/URL).
        for k in FIXED_KEYS:
            translations[f"liveBrowser.{k}"] = EN[f"liveBrowser.{k}"]
        # Every EN key must exist in the locale.
        missing = [k for k in EN if k not in translations]
        if missing:
            raise SystemExit(f"{locale}: missing translations {missing}")
        data.update(translations)
        with open(path, "w") as f:
            json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
            f.write("\n")

    # Compile: {id: message} flattened, sorted (verified identical to
    # formatjs compile output for these catalogs).
    os.makedirs(COMPILED, exist_ok=True)
    locales = sorted(
        f[:-5] for f in os.listdir(MESSAGES) if f.endswith(".json")
    )
    for locale in locales:
        with open(os.path.join(MESSAGES, f"{locale}.json")) as f:
            data = json.load(f)
        compiled = {k: v["defaultMessage"] if isinstance(v, dict) else v for k, v in data.items()}
        with open(os.path.join(COMPILED, f"{locale}.json"), "w") as f:
            json.dump(compiled, f, ensure_ascii=False, indent=2, sort_keys=True)
            f.write("\n")
    print(f"OK: updated {len(EN)} liveBrowser keys in {len(locales)} catalogs")


if __name__ == "__main__":
    main()
